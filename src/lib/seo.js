export function getPage(path) {
  const page = PAGES.find((entry) => entry.path === path);
  if (!page) throw new Error(`Missing SEO registry entry: ${path}`);
  return page;
}

export function getMenuItems(group) {
  return PAGES.filter((page) => !page.noindex && page.menu?.group === group)
    .map((page) => ({ label: page.menu.label, to: page.path }));
}

export function buildMetadata({ path, description, absoluteTitle, type } = {}) {
  const page = getPage(path);
  const title = page.title;
  const fullTitle = (absoluteTitle ?? page.absoluteTitle) ? title : `${title} · ${SITE_NAME}`;
  const canonical = new URL(path, SITE_URL).href;
  const summary = description ?? page.description;
  const ogType = type ?? "website";
  const image = new URL(page.image || "/RicePurityTest.webp", SITE_URL).href;
  return {
    title: { absolute: fullTitle },
    description: summary,
    alternates: {
      canonical,
      ...(["/", "/rice-purity-test-in-spanish"].includes(path) ? {
        languages: { en: SITE_URL + "/", es: SITE_URL + "/rice-purity-test-in-spanish" },
      } : {}),
    },
    robots: { index: !page.noindex, follow: true },
    openGraph: {
      title: fullTitle, description: summary, url: canonical, type: ogType,
      siteName: SITE_NAME, images: [{ url: image, alt: title }],
      ...(ogType === "article" && page.published ? { publishedTime: page.published } : {}),
      ...(ogType === "article" && page.modified ? { modifiedTime: page.modified } : {}),
    },
    twitter: { card: "summary_large_image", title: fullTitle, description: summary, images: [image] },
  };
}
